CHANNELS = ("微信", "抖音", "朋友圈", "线下", "其他")
DECISIONS = {
    "preference": "observe",
    "busy_reason": "support",
    "invitation": "advance",
    "boundary": "stop",
    "background": "observe",
    "correction": "clarify",
}


def cases() -> list[dict[str, Any]]:
    result: list[dict[str, Any]] = []
    development_position = 0
    frozen_position = 0
    for category_index, (category, rows) in enumerate(ROWS.items()):
        if len(rows) != 20:
            raise RuntimeError(f"benchmark category {category} must have 20 rows")
        for row_index, (document, semantic_topic, exact_phrase) in enumerate(rows):
            development = row_index < 6 or (row_index == 6 and category_index < 4)
            if development:
                query_kind = "semantic" if development_position % 2 == 0 else "exact"
                development_position += 1
            else:
                query_kind = "semantic" if frozen_position % 2 == 0 else "exact"
                frozen_position += 1
            query = f"对方关于{semantic_topic}的情况是什么" if query_kind == "semantic" else exact_phrase
            superseded_text = ""
            supersedes_event_id = None
            if category == "correction":
                superseded_text = document.split("之前记录", 1)[1].split("不准确", 1)[0].strip("，,。 ")
                supersedes_event_id = 121 + row_index
                superseded_anchor = f"CORRECTION-ARCHIVE-{row_index + 1:02d}"
            else:
                superseded_anchor = ""
            result.append(
                {
                    "case_id": f"{category}-{row_index + 1:02d}",
                    "category": category,
                    "split": "development" if development else "frozen",
                    "query_kind": query_kind,
                    "query": query,
                    "document": f"{document}。",
                    "search_enrichment": {
                        "summary": document,
                        "concepts": [semantic_topic],
                        "aliases": [semantic_topic, exact_phrase],
                        "entities": [exact_phrase],
                        "time_hints": [],
                    },
                    "expected_decision": DECISIONS[category],
                    "expected_event_id": len(result) + 1,
                    "supersedes_event_id": supersedes_event_id,
                    "superseded_document": (
                        f"{superseded_anchor} 旧记录：{superseded_text}。" if superseded_text else None
                    ),
                    "superseded_query": superseded_anchor or None,
                    "relationship_id": 1 + (row_index % 2),
                    "channel": CHANNELS[row_index % len(CHANNELS)],
                    "explicit_channel": row_index % 4 == 0,
                }
            )
    if len(result) != 120 or sum(item["split"] == "development" for item in result) != 40:
        raise RuntimeError("benchmark split construction failed")
    frozen = [item for item in result if item["split"] == "frozen"]
    if sum(item["query_kind"] == "semantic" for item in frozen) != 40:
        raise RuntimeError("frozen semantic split construction failed")
    return result
